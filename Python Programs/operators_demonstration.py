# Perform arithmetic, relational, logical, and bitwise operations
a, b = 12, 5

print("--- Arithmetic ---")
print("Sum:", a + b, "| Diff:", a - b, "| Prod:", a * b, "| Div:", a / b, "| Mod:", a % b)

print("--- Relational ---")
print("a > b:", a > b, "| a == b:", a == b, "| a != b:", a != b)

print("--- Logical ---")
print("True and False:", True and False, "| True or False:", True or False)

print("--- Bitwise ---")
print("AND:", a & b, "| OR:", a | b, "| XOR:", a ^ b, "| Shift:", a << 1)
