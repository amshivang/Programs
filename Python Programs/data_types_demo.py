# Demonstrate different data types and use type() function
i = 10
f = 3.14
s = "Hello"
b = True
l = [1, 2, 3]
t = (4, 5, 6)
d = {"a": 1}
st = {7, 8, 9}

print("i:", type(i))
print("f:", type(f))
print("s:", type(s))
print("b:", type(b))
print("l:", type(l))
print("t:", type(t))
print("d:", type(d))
print("st:", type(st))
